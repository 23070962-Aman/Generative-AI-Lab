import numpy as np
# HuggingFace pipeline for Question Answering
from transformers import pipeline

# Define the text database containing college rules
college_context = """
Welcome to the Computer Technology Department regulations guide.
To pass a semester, a student must secure a minimum of 40% marks in both internal assessments and external university examinations.
The minimum attendance criteria required to appear for the final examination is 75% for each subject.
If a student falls below 75% without a valid medical certificate, they will be detained.
The mini-project submission deadline for the 5th semester is November 20th.
Late submissions will face a penalty reduction of 2 marks per day.
"""
print("Context Database Loaded Successfully.")

import torch
from transformers import AutoTokenizer, AutoModelForQuestionAnswering

# Load the tokenizer and model directly
model_name = "deepset/bert-base-cased-squad2"
tokenizer = AutoTokenizer.from_pretrained(model_name)
model = AutoModelForQuestionAnswering.from_pretrained(model_name)

# Define a helper function to replicate the QA pipeline behavior
def qa_pipeline(question, context):
    inputs = tokenizer(question, context, return_tensors="pt")
    with torch.no_grad():
        outputs = model(**inputs)

    # Get the start and end of the answer span
    start_idx = torch.argmax(outputs.start_logits)
    end_idx = torch.argmax(outputs.end_logits) + 1

    # Convert tokens back to text
    answer_tokens = inputs["input_ids"][0][start_idx:end_idx]
    answer = tokenizer.convert_tokens_to_string(tokenizer.convert_ids_to_tokens(answer_tokens))

    # Calculate an approximate confidence score
    start_prob = torch.softmax(outputs.start_logits, dim=1)[0][start_idx].item()
    end_prob = torch.softmax(outputs.end_logits, dim=1)[0][end_idx-1].item()
    score = start_prob * end_prob

    return {"answer": answer, "score": score}

print("BERT QA Model and Helper Function Loaded Successfully.")

# Step 5: Define student questions
student_queries = [
    "What is the minimum attendance required for the final exam?",
    "When is the deadline for the 5th semester mini-project?",
    "What is the minimum passing percentage?",
    "What is the penalty for late submission?",
    "What happens if attendance is below 75% without a medical certificate?"
]

# Step 6: Answer each question
for question in student_queries:
    result = qa_pipeline(
        question=question,
        context=college_context
    )

    answer = result["answer"]
    confidence = result["score"]

    print("\nStudent Question:", question)
    print("Predicted Answer:", answer)
    print("Confidence Score:", round(float(confidence), 4))